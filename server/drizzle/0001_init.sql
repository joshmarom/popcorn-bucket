CREATE OR REPLACE FUNCTION sync_show_genres() RETURNS trigger AS $$
BEGIN
  DELETE FROM show_genres WHERE show_id = NEW.tmdb_id;
  IF NEW.genres_json IS NOT NULL AND NEW.genres_json <> '' THEN
    INSERT INTO show_genres (show_id, name)
    SELECT NEW.tmdb_id, value
    FROM json_array_elements_text(NEW.genres_json::json) AS value
    ON CONFLICT DO NOTHING;
  END IF;
  RETURN NEW;
END $$ LANGUAGE plpgsql;

DROP TRIGGER IF EXISTS shows_sync_genres ON shows;
CREATE TRIGGER shows_sync_genres
  AFTER INSERT OR UPDATE OF genres_json ON shows
  FOR EACH ROW EXECUTE FUNCTION sync_show_genres();
