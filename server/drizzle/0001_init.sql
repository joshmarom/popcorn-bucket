-- Catalog tables mirror the desktop SQLite library so the existing SQL can run here.
-- Epoch milliseconds are bigint. Third-party API keys are ciphertext in app_secrets.

CREATE TABLE IF NOT EXISTS schema_migrations (
  id text PRIMARY KEY,
  applied_at timestamptz NOT NULL DEFAULT now()
);

-- The desktop library migration stops once this version is present.
CREATE TABLE IF NOT EXISTS schema_version (
  version integer PRIMARY KEY
);
INSERT INTO schema_version (version) VALUES (5) ON CONFLICT DO NOTHING;

CREATE TABLE IF NOT EXISTS movies (
  tmdb_id integer PRIMARY KEY,
  title text NOT NULL,
  year integer,
  imdb_id text,
